#!/usr/bin/env python3
"""Resize generated backgrounds and compile immutable device RGB565 assets."""
from pathlib import Path
from PIL import Image, ImageOps

ROOT = Path(__file__).resolve().parents[1]
directory = ROOT / 'assets/backgrounds'
names = ('seaside-tea', 'moonlit-dream')
output = ['/* Generated by tools/compile_backgrounds.py. Pixels stay in flash. */',
          '#include "whale_backgrounds.h"', '']
for index, name in enumerate(names):
    with Image.open(directory / f'{name}-source.png') as original:
        frame = ImageOps.fit(original.convert('RGB'), (240, 320), method=Image.Resampling.LANCZOS)
    frame.save(directory / f'{name}.png', optimize=True)
    raw = bytearray()
    for r, g, b in frame.get_flattened_data():
        value = (r >> 3) << 11 | (g >> 2) << 5 | b >> 3
        raw.extend((value & 255, value >> 8))
    output.append(f'static const uint8_t LV_ATTRIBUTE_MEM_ALIGN pixels_{index}[] = {{')
    for offset in range(0, len(raw), 32):
        output.append('  ' + ','.join(f'0x{v:02x}' for v in raw[offset:offset+32]) + ',')
    output.extend(['};', f'static const lv_image_dsc_t background_{index} = {{',
                   '  .header = { .magic = LV_IMAGE_HEADER_MAGIC, .cf = LV_COLOR_FORMAT_RGB565,',
                   '    .w = 240, .h = 320, .stride = 480 },',
                   f'  .data_size = sizeof(pixels_{index}), .data = pixels_{index},', '};', ''])
output.extend(['const lv_image_dsc_t *const whale_backgrounds[2] = { &background_0, &background_1 };', ''])
(directory / 'whale_backgrounds.c').write_text('\n'.join(output), encoding='utf-8')
print('Backgrounds: 2 x 240x320 RGB565 = 307,200 flash bytes, no PNG decoder')
