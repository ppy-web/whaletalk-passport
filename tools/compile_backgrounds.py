#!/usr/bin/env python3
"""Compile indexed backgrounds into 16-row Deflate bands shared by the display and portal."""
from io import BytesIO
from pathlib import Path
import struct
import zlib
from PIL import Image, ImageOps
from compile_whale_avatar import BAND_ROWS, pack_indexed_bands

ROOT = Path(__file__).resolve().parents[1]
directory = ROOT / 'assets/backgrounds'
names = ('seaside-tea', 'moonlit-dream')
seasons = ('spring-sakura', 'summer-shore', 'autumn-maple', 'winter-snow')
output = ['/* Generated by tools/compile_backgrounds.py. Pixels stay in flash. */',
          '#include "whale_backgrounds.h"', '']


def verify_bmp_roundtrip(expected_bmp, payload, width, height):
    """Verify reconstructing the standard 8-bit BMP from BGR palette + Deflate bands is byte-identical."""
    bgr_palette = payload[:256 * 3]
    band_payload = payload[256 * 3:]
    bands = (height + BAND_ROWS - 1) // BAND_ROWS
    table_bytes = (bands + 1) * 2
    offsets = struct.unpack_from(f'<{bands + 1}H', band_payload, 0)
    top_down = bytearray()
    for b in range(bands):
        rows = min(BAND_ROWS, height - b * BAND_ROWS)
        chunk = band_payload[table_bytes + offsets[b]:table_bytes + offsets[b + 1]]
        dec = zlib.decompress(chunk, -15)
        if len(dec) != rows * width:
            raise ValueError('Background band size mismatch')
        top_down.extend(dec)
    bottom_up = b''.join(
        top_down[(height - 1 - y) * width:(height - y) * width]
        for y in range(height)
    )
    image_bytes = width * height
    header = struct.pack(
        '<2sIHHIIiiHHIIiiII',
        b'BM', 1078 + image_bytes, 0, 0, 1078,
        40, width, height, 1, 8, 0, image_bytes, 3780, 3780, 256, 256,
    )
    pal_bgr0 = b''.join(bgr_palette[i * 3:i * 3 + 3] + b'\x00' for i in range(256))
    if header + pal_bgr0 + bottom_up != expected_bmp:
        raise ValueError('Reconstructed BMP does not match Pillow output byte-for-byte')


def pack_bmp_bands(bmp_raw, width, height):
    bgr_palette = b''.join(bmp_raw[54 + i * 4:54 + i * 4 + 3] for i in range(256))
    top_down = b''.join(
        bmp_raw[1078 + (height - 1 - y) * width:1078 + (height - y) * width]
        for y in range(height)
    )
    payload = bgr_palette + pack_indexed_bands(top_down, width, height)
    verify_bmp_roundtrip(bmp_raw, payload, width, height)
    return payload


def emit(index, raw, width, height):
    output.append(f'static const uint8_t LV_ATTRIBUTE_MEM_ALIGN pixels_{index}[] = {{')
    for offset in range(0, len(raw), 32):
        output.append('  ' + ','.join(f'0x{v:02x}' for v in raw[offset:offset + 32]) + ',')
    output.extend(['};', f'static const lv_image_dsc_t background_{index} = {{',
                   '  .header = { .magic = LV_IMAGE_HEADER_MAGIC, .cf = LV_COLOR_FORMAT_RAW,',
                   f'    .w = {width}, .h = {height}, .stride = 0 }},',
                   f'  .data_size = sizeof(pixels_{index}), .data = pixels_{index},', '};', ''])


day_night_bytes = 0
for index, name in enumerate(names):
    with Image.open(directory / f'{name}-source.png') as original:
        frame = ImageOps.fit(original.convert('RGB'), (240, 320), method=Image.Resampling.LANCZOS)
    indexed = frame.quantize(colors=256, method=Image.Quantize.MEDIANCUT)
    indexed.save(directory / f'{name}.png', optimize=True)
    image = BytesIO()
    indexed.save(image, 'BMP')
    raw = image.getvalue()
    if (raw[:2] != b'BM' or len(raw) != 1078 + 240 * 320
            or struct.unpack_from('<IIiiHHI', raw, 10) != (1078, 40, 240, 320, 1, 8, 0)):
        raise ValueError(f'Unexpected indexed BMP layout for {name}')
    packed = pack_bmp_bands(raw, 240, 320)
    day_night_bytes += len(packed)
    emit(index, packed, 240, 320)

seasonal_bytes = 0
for index, name in enumerate(seasons, start=len(names)):
    with Image.open(directory / 'examples' / f'{name}.png') as original:
        frame = original.convert('RGB').resize((120, 160), Image.Resampling.LANCZOS)
        indexed = frame.quantize(colors=256, method=Image.Quantize.MEDIANCUT)
    image = BytesIO()
    indexed.save(image, 'BMP')
    raw = image.getvalue()
    if (raw[:2] != b'BM' or len(raw) != 1078 + 120 * 160
            or struct.unpack_from('<IIiiHHI', raw, 10) != (1078, 40, 120, 160, 1, 8, 0)):
        raise ValueError(f'Unexpected indexed BMP layout for {name}')
    packed = pack_bmp_bands(raw, 120, 160)
    seasonal_bytes += len(packed)
    emit(index, packed, 120, 160)

output.append('const lv_image_dsc_t *const whale_backgrounds[ONLINE_BACKGROUND_COUNT] = {')
for index, key in enumerate(('DAY', 'NIGHT', 'SPRING', 'SUMMER', 'AUTUMN', 'WINTER')):
    output.append(f'  [ONLINE_BACKGROUND_{key}] = &background_{index},')
output.extend(['};', ''])
(directory / 'whale_backgrounds.c').write_text('\n'.join(output), encoding='utf-8')
print(f'Backgrounds: {day_night_bytes:,} day/night bytes and {seasonal_bytes:,} seasonal bytes in flash')
