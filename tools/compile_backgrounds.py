#!/usr/bin/env python3
"""Compile original RGB565 and shared indexed BMP background assets."""
from io import BytesIO
from pathlib import Path
from struct import unpack_from
from PIL import Image, ImageOps

ROOT = Path(__file__).resolve().parents[1]
directory = ROOT / 'assets/backgrounds'
names = ('seaside-tea', 'moonlit-dream')
seasons = ('spring-sakura', 'summer-shore', 'autumn-maple', 'winter-snow')
output = ['/* Generated by tools/compile_backgrounds.py. Pixels stay in flash. */',
          '#include "whale_backgrounds.h"', '']


def emit(index, raw, color_format, stride):
    output.append(f'static const uint8_t LV_ATTRIBUTE_MEM_ALIGN pixels_{index}[] = {{')
    for offset in range(0, len(raw), 32):
        output.append('  ' + ','.join(f'0x{v:02x}' for v in raw[offset:offset+32]) + ',')
    output.extend(['};', f'static const lv_image_dsc_t background_{index} = {{',
                   f'  .header = {{ .magic = LV_IMAGE_HEADER_MAGIC, .cf = {color_format},',
                   f'    .w = 240, .h = 320, .stride = {stride} }},',
                   f'  .data_size = sizeof(pixels_{index}), .data = pixels_{index},', '};', ''])


for index, name in enumerate(names):
    with Image.open(directory / f'{name}-source.png') as original:
        frame = ImageOps.fit(original.convert('RGB'), (240, 320), method=Image.Resampling.LANCZOS)
    frame.save(directory / f'{name}.png', optimize=True)
    raw = bytearray()
    for r, g, b in frame.get_flattened_data():
        value = (r >> 3) << 11 | (g >> 2) << 5 | b >> 3
        raw.extend((value & 255, value >> 8))
    emit(index, raw, 'LV_COLOR_FORMAT_RGB565', 480)

seasonal_bytes = 0
for index, name in enumerate(seasons, start=len(names)):
    with Image.open(directory / 'examples' / f'{name}.png') as original:
        frame = original.convert('RGB').resize((120, 160), Image.Resampling.LANCZOS)
        indexed = frame.quantize(colors=256, method=Image.Quantize.MEDIANCUT)
    image = BytesIO()
    indexed.save(image, 'BMP')
    raw = image.getvalue()
    # The device reads fixed BMP offsets and bottom-up rows of 120 I8 pixels.
    if (raw[:2] != b'BM' or len(raw) != 1078 + 120 * 160
            or unpack_from('<IIiiHHI', raw, 10) != (1078, 40, 120, 160, 1, 8, 0)):
        raise ValueError(f'Unexpected indexed BMP layout for {name}')
    emit(index, raw, 'LV_COLOR_FORMAT_RAW', 0)
    seasonal_bytes += len(raw)

output.append('const lv_image_dsc_t *const whale_backgrounds[ONLINE_BACKGROUND_COUNT] = {')
for index, key in enumerate(('DAY', 'NIGHT', 'SPRING', 'SUMMER', 'AUTUMN', 'WINTER')):
    output.append(f'  [ONLINE_BACKGROUND_{key}] = &background_{index},')
output.extend(['};', ''])
(directory / 'whale_backgrounds.c').write_text('\n'.join(output), encoding='utf-8')
print(f'Backgrounds: 307,200 RGB565 bytes and {seasonal_bytes:,} indexed seasonal bytes in flash')
