#!/usr/bin/env python3
"""Compile the home artwork using the shared palette/scanline image format."""
from pathlib import Path
import struct
from PIL import Image
from compile_whale_avatar import pack_row

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'assets/ui/home-foreground.png'
OUTPUT = ROOT / 'assets/ui/home_foreground.c'
WIDTH, HEIGHT = 240, 320
REGIONS = (('top', 0, 35), ('bottom', 268, 320))


def compile_region(image):
    indexed = image.quantize(colors=256, method=Image.Quantize.FASTOCTREE)
    palette = indexed.getpalette('RGBA')
    data = bytearray()
    for index in range(256):
        r, g, b, a = palette[index * 4:index * 4 + 4]
        pixel = (r >> 3) << 11 | (g >> 2) << 5 | b >> 3
        data.extend((pixel & 255, pixel >> 8, a))
    indices = indexed.tobytes()
    rows = bytearray()
    offsets = [0]
    for offset in range(0, len(indices), WIDTH):
        rows.extend(pack_row(indices[offset:offset + WIDTH]))
        offsets.append(len(rows))
    if len(rows) > 65535:
        raise ValueError('Foreground row data exceeds the uint16 offset limit')
    return data + struct.pack(f'<{len(offsets)}H', *offsets) + rows


def main():
    with Image.open(SOURCE) as source:
        if source.mode != 'RGBA' or source.width * 4 != source.height * 3:
            raise ValueError('Expected a transparent, portrait 3:4 source')
        image = source.resize((WIDTH, HEIGHT), Image.Resampling.LANCZOS)
    output = ['/* Generated by tools/compile_home_foreground.py; indexed rows in flash. */',
              '#include "home_foreground.h"', '']
    total = 0
    for name, top, bottom in REGIONS:
        data = compile_region(image.crop((0, top, WIDTH, bottom)))
        total += len(data)
        output.append(f'static const uint8_t LV_ATTRIBUTE_MEM_ALIGN {name}_pixels[] = {{')
        for offset in range(0, len(data), 32):
            output.append('  ' + ','.join(f'0x{value:02x}' for value in data[offset:offset + 32]) + ',')
        output.extend(['};', f'const lv_image_dsc_t home_foreground_{name} = {{',
                       '  .header = { .magic = LV_IMAGE_HEADER_MAGIC, .cf = LV_COLOR_FORMAT_RAW,',
                       f'    .w = {WIDTH}, .h = {bottom-top} }},',
                       f'  .data_size = sizeof({name}_pixels), .data = {name}_pixels,', '};', ''])
    OUTPUT.write_text('\n'.join(output), encoding='utf-8')
    print(f'Compiled {OUTPUT}: {total:,} bytes')


if __name__ == '__main__':
    main()
