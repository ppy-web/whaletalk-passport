#!/usr/bin/env python3
"""Compile the generated 3x2 atlas to flash-resident LVGL RGB565 frames."""
from pathlib import Path
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
NAMES = ('idle', 'listening', 'thinking', 'speaking', 'blink', 'error')
SIZE = 192


def main():
    directory = ROOT / 'assets/characters'
    with Image.open(directory / 'whale-girl-atlas.png') as atlas:
        if atlas.width % 3 or atlas.height % 2 or atlas.width // 3 != atlas.height // 2:
            raise ValueError('Expected an equal-square 3x2 expression atlas')
        cell = atlas.width // 3
        output = ['/* Generated by tools/compile_whale_avatar.py; pixels stay in flash. */', '#include "whale_avatar.h"', '']
        for index, name in enumerate(NAMES):
            x, y = index % 3 * cell, index // 3 * cell
            frame = atlas.crop((x, y, x + cell, y + cell)).convert('RGB').resize((SIZE, SIZE), Image.Resampling.LANCZOS)
            frame.save(directory / f'whale-{name}.png')
            raw = bytearray()
            for r, g, b in frame.get_flattened_data():
                value = (r >> 3) << 11 | (g >> 2) << 5 | b >> 3
                raw.extend((value & 255, value >> 8))
            output.append(f'static const uint8_t LV_ATTRIBUTE_MEM_ALIGN pixels_{name}[] = {{')
            for offset in range(0, len(raw), 32):
                output.append('  ' + ','.join(f'0x{value:02x}' for value in raw[offset:offset + 32]) + ',')
            output.extend(['};', f'static const lv_image_dsc_t image_{name} = {{',
                           '  .header = { .magic = LV_IMAGE_HEADER_MAGIC, .cf = LV_COLOR_FORMAT_RGB565,',
                           f'    .w = {SIZE}, .h = {SIZE}, .stride = {SIZE * 2} }},',
                           f'  .data_size = sizeof(pixels_{name}), .data = pixels_{name},', '};', ''])
        output.extend(['const lv_image_dsc_t *const whale_avatar_frames[ONLINE_AVATAR_COUNT] = {',
                       '  ' + ', '.join(f'&image_{name}' for name in NAMES), '};', ''])
        (directory / 'whale_avatar.c').write_text('\n'.join(output), encoding='utf-8')
    print(f'Compiled {len(NAMES)} frames: {SIZE}x{SIZE} RGB565, {len(NAMES) * SIZE * SIZE * 2} flash bytes; no full-frame RAM decoder')


if __name__ == '__main__':
    main()
