#!/usr/bin/env python3
"""Compile built-in expression atlases into flash-resident scanlines."""
from pathlib import Path
import struct
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
NAMES = ('idle', 'listening', 'thinking', 'speaking', 'blink', 'error')
PORTRAIT_SIZE = 280
VIEW_WIDTH, VIEW_HEIGHT = 240, 285
PORTRAIT_TOP, VIEW_TOP = 38, 35
ATLASES = {
    'whale': 'whale-girl-transparent-atlas.png',
    'whale_maid': 'whale-maid-atlas.png',
    'claude': 'claude-atlas.png',
}


def pack_row(row):
    """Pack repeated indices or runs of literals; store dense rows verbatim."""
    def run_end(start):
        end = start + 1
        while end < len(row) and end - start < 128 and row[end] == row[start]:
            end += 1
        return end

    packed = bytearray()
    i = 0
    while i < len(row):
        end = run_end(i)
        count = end - i
        if count >= 3:
            packed.extend((0x80 | (count - 1), row[i]))
        else:
            start = i
            while end < len(row) and end - start < 128 and run_end(end) - end < 3:
                end += 1
            packed.append(end - start - 1)
            packed.extend(row[start:end])
        i = end
    return packed if len(packed) < len(row) else row


def pack_frame(indexed):
    raw = bytearray()
    palette = indexed.getpalette('RGBA')
    for index in range(256):
        r, g, b, a = palette[index * 4:index * 4 + 4]
        value = (r >> 3) << 11 | (g >> 2) << 5 | b >> 3
        raw.extend((value & 255, value >> 8, a))
    indices = indexed.tobytes()
    pixels = bytearray()
    offsets = [0]
    for offset in range(0, len(indices), VIEW_WIDTH):
        pixels.extend(pack_row(indices[offset:offset + VIEW_WIDTH]))
        offsets.append(len(pixels))
    if len(pixels) > 65535:
        raise ValueError('Row data exceeds the uint16 offset limit; use a less dense atlas')
    return raw + struct.pack(f'<{len(offsets)}H', *offsets) + pixels


def compile_atlas(directory, character, source):
    with Image.open(directory / source) as atlas:
        if atlas.width % 3 or atlas.height % 2 or atlas.width // 3 != atlas.height // 2:
            raise ValueError(f'{source}: expected an equal-square 3x2 expression atlas')
        cell = atlas.width // 3
        output = ['/* Generated by tools/compile_whale_avatar.py; pixels stay in flash. */', '#include "whale_avatar.h"', '']
        total_size = 0
        for index, name in enumerate(NAMES):
            x, y = index % 3 * cell, index // 3 * cell
            portrait = atlas.crop((x, y, x + cell, y + cell)).convert('RGBA').resize(
                (PORTRAIT_SIZE, PORTRAIT_SIZE), Image.Resampling.LANCZOS)
            left = (PORTRAIT_SIZE - VIEW_WIDTH) // 2
            top = VIEW_TOP - PORTRAIT_TOP
            frame = portrait.crop((left, top, left + VIEW_WIDTH, top + VIEW_HEIGHT))
            indexed = frame.quantize(colors=256, method=Image.Quantize.FASTOCTREE)
            if character == 'whale':
                indexed.convert('RGBA').save(directory / f'whale-{name}.png')
            raw = pack_frame(indexed)
            total_size += len(raw)
            output.append(f'static const uint8_t LV_ATTRIBUTE_MEM_ALIGN pixels_{name}[] = {{')
            for offset in range(0, len(raw), 32):
                output.append('  ' + ','.join(f'0x{value:02x}' for value in raw[offset:offset + 32]) + ',')
            output.extend(['};', f'static const lv_image_dsc_t image_{name} = {{',
                           '  .header = { .magic = LV_IMAGE_HEADER_MAGIC, .cf = LV_COLOR_FORMAT_RAW,',
                           f'    .w = {VIEW_WIDTH}, .h = {VIEW_HEIGHT} }},',
                           f'  .data_size = sizeof(pixels_{name}), .data = pixels_{name},', '};', ''])
        output.extend([f'const lv_image_dsc_t *const {character}_avatar_frames[ONLINE_AVATAR_COUNT] = {{',
                       '  ' + ', '.join(f'&image_{name}' for name in NAMES), '};', ''])
        (directory / f'{character}_avatar.c').write_text('\n'.join(output), encoding='utf-8')
    print(f'Compiled {len(NAMES)} frames: {VIEW_WIDTH}x{VIEW_HEIGHT}, RGB565+A8 palette/index, '
          f'{total_size:,} flash bytes for {character}; native scanline drawing')


def main():
    directory = ROOT / 'assets/characters'
    for character, source in ATLASES.items():
        compile_atlas(directory, character, source)


if __name__ == '__main__':
    main()
