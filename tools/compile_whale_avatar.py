#!/usr/bin/env python3
"""Compile built-in expression atlases into flash-resident scanlines."""
from pathlib import Path
import struct
from PIL import Image, ImageChops

ROOT = Path(__file__).resolve().parents[1]
NAMES = ('idle', 'listening', 'thinking', 'speaking', 'blink', 'error')
FISH_NAMES = (*NAMES, 'eating', 'speaking_closed', 'speaking_blink', 'speaking_closed_blink')
VIEW_WIDTH, VIEW_HEIGHT = 240, 285
VIEW_TOP = 35
# Atlas file, rendered portrait size, top edge and optional fade start on the display.
ATLASES = {
    'whale': ('big-fat-fish-atlas.png', (216, 288), 38, 295),
    'whale_maid': ('whale-maid-atlas.png', (280, 280), 38, None),
    'claude': ('claude-atlas.png', (280, 280), 38, None),
    'chatgpt': ('chatgpt-atlas.png', (248, 248), 49, 248),
}


def pack_row(row):
    """Pack repeated indices or runs of literals; store dense rows verbatim."""
    def run_end(start):
        end = start + 1
        while end < len(row) and end - start < 128 and row[end] == row[start]:
            end += 1
        return end

    packed = bytearray()
    i = 0
    while i < len(row):
        end = run_end(i)
        count = end - i
        if count >= 3:
            packed.extend((0x80 | (count - 1), row[i]))
        else:
            start = i
            while end < len(row) and end - start < 128 and run_end(end) - end < 3:
                end += 1
            packed.append(end - start - 1)
            packed.extend(row[start:end])
        i = end
    return packed if len(packed) < len(row) else row


def pack_frame(indexed):
    raw = bytearray()
    palette = indexed.getpalette('RGBA')
    for index in range(256):
        r, g, b, a = palette[index * 4:index * 4 + 4]
        value = (r >> 3) << 11 | (g >> 2) << 5 | b >> 3
        raw.extend((value & 255, value >> 8, a))
    indices = indexed.tobytes()
    pixels = bytearray()
    offsets = [0]
    for offset in range(0, len(indices), VIEW_WIDTH):
        pixels.extend(pack_row(indices[offset:offset + VIEW_WIDTH]))
        offsets.append(len(pixels))
    if len(pixels) > 65535:
        raise ValueError('Row data exceeds the uint16 offset limit; use a less dense atlas')
    return raw + struct.pack(f'<{len(offsets)}H', *offsets) + pixels


def bottom_fade(fade_start, portrait_bottom):
    start = fade_start - VIEW_TOP
    end = min(portrait_bottom - VIEW_TOP, VIEW_HEIGHT - 1)
    rows = bytearray()
    for y in range(VIEW_HEIGHT):
        t = min(1, max(0, y - start) / (end - start))
        rows.append(round(255 * (1 - t * t * (3 - 2 * t))))
    return Image.frombytes('L', (1, VIEW_HEIGHT), bytes(rows)).resize(
        (VIEW_WIDTH, VIEW_HEIGHT), Image.Resampling.NEAREST)


def compile_atlas(directory, character, source, portrait_size, portrait_top, fade_start):
    names = FISH_NAMES if character == 'whale' else NAMES
    columns = len(names) // 2
    fade = bottom_fade(fade_start, portrait_top + portrait_size[1] - 1) if fade_start is not None else None
    with Image.open(directory / source) as atlas:
        cell_width, cell_height = atlas.width // columns, atlas.height // 2
        width, height = portrait_size
        if atlas.width % columns or atlas.height % 2 or cell_width * height != cell_height * width:
            raise ValueError(f'{source}: expected a {columns}x2 atlas with {width}:{height} cells')
        left = (width - VIEW_WIDTH) // 2
        top = VIEW_TOP - portrait_top
        viewport = (left, top, left + VIEW_WIDTH, top + VIEW_HEIGHT)
        output = ['/* Generated by tools/compile_whale_avatar.py; pixels stay in flash. */', '#include "whale_avatar.h"', '']
        total_size = 0
        for index, name in enumerate(names):
            x, y = index % columns * cell_width, index // columns * cell_height
            portrait = atlas.crop((x, y, x + cell_width, y + cell_height)).convert('RGBA').resize(
                portrait_size, Image.Resampling.LANCZOS)
            frame = portrait.crop(viewport)
            if fade is not None:
                frame.putalpha(ImageChops.multiply(frame.getchannel('A'), fade))
            indexed = frame.quantize(colors=256, method=Image.Quantize.FASTOCTREE)
            if character == 'whale':
                indexed.convert('RGBA').save(directory / f'whale-{name}.png')
            raw = pack_frame(indexed)
            total_size += len(raw)
            output.append(f'static const uint8_t LV_ATTRIBUTE_MEM_ALIGN pixels_{name}[] = {{')
            for offset in range(0, len(raw), 32):
                output.append('  ' + ','.join(f'0x{value:02x}' for value in raw[offset:offset + 32]) + ',')
            output.extend(['};', f'static const lv_image_dsc_t image_{name} = {{',
                           '  .header = { .magic = LV_IMAGE_HEADER_MAGIC, .cf = LV_COLOR_FORMAT_RAW,',
                           f'    .w = {VIEW_WIDTH}, .h = {VIEW_HEIGHT} }},',
                           f'  .data_size = sizeof(pixels_{name}), .data = pixels_{name},', '};', ''])
        output.extend([f'const lv_image_dsc_t *const {character}_avatar_frames[ONLINE_AVATAR_COUNT] = {{',
                       '  ' + ', '.join(f'&image_{name}' for name in names), '};', ''])
        (directory / f'{character}_avatar.c').write_text('\n'.join(output), encoding='utf-8')
    print(f'Compiled {len(names)} frames: {VIEW_WIDTH}x{VIEW_HEIGHT}, RGB565+A8 palette/index, '
          f'{total_size:,} flash bytes for {character}; native scanline drawing')


def main():
    directory = ROOT / 'assets/characters'
    for character, layout in ATLASES.items():
        compile_atlas(directory, character, *layout)


if __name__ == '__main__':
    main()
